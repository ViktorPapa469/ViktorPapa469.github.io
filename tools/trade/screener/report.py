def e(x):
    return html.escape(str(x))


def money(x, d=2):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "–"
    return f"₹{x:,.{d}f}"


def num(x, d=2, sign=False, suffix=""):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "–"
    return f"{x:{'+' if sign else ''},.{d}f}{suffix}"


def cls(x):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return ""
    return "up" if x > 0 else ("dn" if x < 0 else "")


def page(title, body):
    return (f"<!doctype html><html lang='en'><head><meta charset='utf-8'>"
            f"<meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>{e(title)}</title><style>{CSS}</style></head><body><main>{body}"
            f"<footer>Generated by your NSE screener. Data from NSE and Yahoo Finance may be delayed or "
            f"incomplete. This is a screening aid, not investment advice - verify levels on your broker "
            f"terminal before trading.</footer></main></body></html>")


def kpi(label, value, extra=""):
    return f"<div class='kpi'><div class='l'>{e(label)}</div><div class='v'>{value}</div>{extra}</div>"


# ------------------------------------------------------------------ premarket
def premarket(ctx):
    reg, res = ctx["regime"], ctx["result"]
    badge = {"Uptrend": "b-up", "Downtrend": "b-dn"}.get(reg["label"], "b-warn")
    head = (f"<h1>Morning watchlist</h1><div class='sub'>{e(ctx['today'])} · "
            f"prices to close of {e(ctx['as_of'])} · generated {e(ctx['generated'])} IST"
            f"{' · <b>DEMO DATA</b>' if ctx['demo'] else ''}</div>")
    nav = ("<nav><a href='#market'>Market</a><a href='#sectors'>Sectors</a><a href='#longs'>Longs</a>"
           "<a href='#shorts'>Shorts</a><a href='#pullbacks'>Pullbacks</a><a href='#bases'>Bases</a>"
           "<a href='#events'>Results</a><a href='#rules'>Rules</a></nav>")

    # market card
    k = [kpi("Nifty 50", num(reg.get("nifty"), 0),
             f"<div class='{cls(reg.get('nifty_chg'))}'>{num(reg.get('nifty_chg'), 2, True, '%')}</div>"),
         kpi("vs 20 EMA", f"<span class='{cls(reg.get('nifty_vs20'))}'>{num(reg.get('nifty_vs20'), 1, True, '%')}</span>"),
         kpi("Bank Nifty", num(reg.get("bank"), 0),
             f"<div class='{cls(reg.get('bank_chg'))}'>{num(reg.get('bank_chg'), 2, True, '%')}</div>"),
         kpi("India VIX", num(reg.get("vix"), 2),
             f"<div class='{cls(-(reg.get('vix_chg') or 0))}'>{num(reg.get('vix_chg'), 1, True, '%')}</div>")]
    po = ctx.get("preopen_breadth")
    if po:
        k.append(kpi("Pre-open F&O", f"{po['adv']}↑ {po['dec']}↓", f"<div class='{cls(po['avg'])}'>avg {num(po['avg'], 2, True, '%')}</div>"))
    for f in ctx["fii_dii"]:
        k.append(kpi(f"{f['category']} net", f"<span class='{cls(f['net_cr'])}'>{num(f['net_cr'], 0, True)} cr</span>",
                     f"<div class='sub'>{e(f['date'])}</div>"))
    cues = "".join(f"<span class='chip'>{e(c['name'])} <b class='{cls(c['chg_pct'])}'>{num(c['chg_pct'], 2, True, '%')}</b></span>"
                   for c in ctx["cues"]) or "<span class='empty'>unavailable</span>"
    risk_amt = C.CAPITAL * C.RISK_PCT / 100 * reg.get("size_mult", 1)
    market = (f"<h2 id='market'>Market regime</h2><div class='card'>"
              f"<div class='row'><span class='badge {badge}'>{e(reg['label'])}</span>"
              f"<span class='sub'>size × {reg.get('size_mult', 1):g} → risk {money(risk_amt, 0)}/trade</span></div>"
              f"<p style='margin:8px 0 12px'>{e(reg['bias'])}</p><div class='grid'>{''.join(k)}</div>"
              f"<div style='margin-top:12px' class='sub'>Global cues</div><div class='cues' style='margin-top:6px'>{cues}</div></div>")

    # sectors
    sec = res["sectors"]
    if len(sec):
        mx = max(sec["score"].abs().max(), 1e-9)
        rows = []
        for name, r in sec.iterrows():
            w = abs(r["score"]) / mx * 50
            left = 50 if r["score"] >= 0 else 50 - w
            color = "var(--up)" if r["score"] >= 0 else "var(--dn)"
            rows.append(f"<div class='sec'><span class='t'>{e(name)} <span class='sub'>({int(r['n'])})</span></span>"
                        f"<span class='track'><i style='left:{left:.1f}%;width:{w:.1f}%;background:{color}'></i></span>"
                        f"<span class='num {cls(r['rs20'])}'>{num(r['rs20'], 1, True, '%')}</span></div>")
        sectors = (f"<h2 id='sectors'>Sector strength</h2><div class='card'><div class='sub' style='margin-bottom:6px'>"
                   f"Median 20-day return vs Nifty (bar blends 20d and 5d)</div>{''.join(rows)}</div>")
    else:
        sectors = "<h2 id='sectors'>Sector strength</h2><div class='card empty'>No sector data</div>"

    longs = _section("longs", "Intraday longs", res["longs"], _intraday_card,
                     "Plan: after 9:30 buy only above the 15-min opening-range high, with price above VWAP and the stock stronger than Nifty.")
    shorts = _section("shorts", "Intraday shorts", res["shorts"], _intraday_card,
                      "Plan: after 9:30 short only below the 15-min opening-range low, with price below VWAP and the stock weaker than Nifty.")
    pull = _section("pullbacks", "Swing: pullbacks to 20 EMA", res["pullbacks"], _swing_card,
                    "Buy only if price trades above the trigger (yesterday's high). No trigger, no trade.")
    bases = _section("bases", "Swing: tight bases near highs", res["bases"], _swing_card,
                     "Buy only on a break above the 10-day high with volume.")

    ev = ctx["events"]
    if len(ev):
        items = "".join(f"<div class='row' style='padding:4px 0'><span><b>{e(r['symbol'])}</b> "
                        f"<span class='sub'>{e(r['purpose'])}</span></span><span class='sub'>{e(r['date'])}</span></div>"
                        for _, r in ev.iterrows())
        events = f"<h2 id='events'>F&amp;O results calendar</h2><div class='card'>{items}</div>"
    else:
        events = "<h2 id='events'>F&amp;O results calendar</h2><div class='card empty'>No F&amp;O results in the window</div>"

    rules = (f"<h2 id='rules'>Today's rules</h2><div class='card'><ul class='rules'>"
             f"<li>No trades in the first {C.ORB_MINUTES} minutes. Run <code>python run.py orb --watch</code> at 9:31.</li>"
             f"<li>Risk {money(risk_amt, 0)} per trade. Stop trading after a loss of {money(risk_amt * C.DAILY_LOSS_LIMIT_R, 0)} ({C.DAILY_LOSS_LIMIT_R}R).</li>"
             f"<li>Book half at 1.5–2R, trail the rest. Never average down.</li>"
             f"<li>If Nifty is stuck inside its opening range, sit out.</li>"
             f"<li>Skip names with results today unless trading the reaction after 10:00.</li></ul></div>")
    meta = (f"<div class='sub' style='margin-top:20px'>Universe: {ctx['universe']} F&amp;O stocks · "
            f"{ctx['priced']} with price history · {res['liquid_count']} pass liquidity/ATR filters"
            f"{' · OI from F&amp;O bhavcopy ' + e(ctx['oi_date']) if ctx.get('oi_date') else ' · OI unavailable'}</div>")
    return page(f"Watchlist {ctx['today']}", head + nav + market + sectors + longs + shorts + pull + bases + events + rules + meta)


def _section(anchor, title, items, card_fn, note):
    body = "".join(card_fn(x) for x in items) or "<div class='card empty'>No names qualify today.</div>"
    return f"<h2 id='{anchor}'>{e(title)} <span class='sub'>({len(items)})</span></h2><div class='sub'>{e(note)}</div>{body}"


def _head(x):
    lot = f" · lot {int(x['lot'])}" if x.get("lot") and not math.isnan(x["lot"]) else ""
    return (f"<div class='row'><div><span class='sym'>{e(x['symbol'])}</span> "
            f"<span class='ind'>{e(x['industry'])}{lot}</span></div>"
            f"<div class='num'>{money(x['price'])} <span class='{cls(x['chg1'])}'>{num(x['chg1'], 2, True, '%')}</span></div></div>")


def _chips(x):
    return "<div class='chips'>" + "".join(f"<span class='chip'>{e(r)}</span>" for r in x["reasons"]) + "</div>"


def _warns(x):
    return "".join(f"<div class='warn'>⚠ {e(w)}</div>" for w in x.get("warnings", []))


def _lv(pairs):
    return "<div class='lv'>" + "".join(f"<div><div class='l'>{e(a)}</div><div class='v'>{b}</div></div>" for a, b in pairs) + "</div>"


def _intraday_card(x):
    gap = num(x["gap_pct"], 2, True, "%") if x.get("gap_pct") is not None else "–"
    lv = _lv([("Prev high", money(x["pdh"])), ("Prev low", money(x["pdl"])), ("ATR", money(x["atr"])),
              ("Pre-open gap", gap), ("Est. qty*", f"{x['est_qty']:,}")])
    return (f"<div class='card'>{_head(x)}{_chips(x)}{lv}{_warns(x)}"
            f"<div class='score'><i style='width:{x['score']:.0f}%'></i></div>"
            f"<div class='sub' style='margin-top:4px'>Score {x['score']:.0f} · *qty assumes a stop ≈ ½ ATR "
            f"({money(x['est_stop_dist'])}); exact stop comes from the opening range</div></div>")


def _swing_card(x):
    lv = _lv([("Trigger", money(x["entry"])), ("Stop", money(x["stop"])), ("Target 2R", money(x["t1"])),
              ("Target 3R", money(x["t2"])), ("Risk", num(x["risk_pct"], 1, False, "%")), ("Qty", f"{x['qty']:,}")])
    return (f"<div class='card'>{_head(x)}{_chips(x)}{lv}{_warns(x)}"
            f"<div class='score'><i style='width:{x['score']:.0f}%'></i></div>"
            f"<div class='sub' style='margin-top:4px'>Score {x['score']:.0f}</div></div>")


# ------------------------------------------------------------------ live ORB
def orb(ctx):
    res = ctx["orb"]
    nchg = res["nifty_chg"]
    nv = res["nifty_above_vwap"]
    head = (f"<h1>Opening-range scan</h1><div class='sub'>{e(ctx['today'])} · bars to "
            f"{e(res['as_of'].strftime('%H:%M') if res['as_of'] is not None else '–')} · generated {e(ctx['generated'])} IST"
            f"{' · <b>DEMO DATA</b>' if ctx['demo'] else ''}</div>")
    k = kpi("Nifty since open", f"<span class='{cls(nchg)}'>{num(nchg, 2, True, '%')}</span>")
    if nv is not None:
        k += kpi("Nifty vs VWAP", "Above" if nv else "Below")
    trig = sum(r["status"].startswith("TRIGGERED") for r in res["rows"])
    k += kpi("Triggered", str(trig)) + kpi("Watching", str(len(res["rows"])))
    cards = []
    for r in res["rows"]:
        st = r["status"]
        b = "b-up" if st == "TRIGGERED" else ("b-dn" if st == "FAILED" else ("b-warn" if "weak" in st else "b-n"))
        side = "LONG" if r["side"] == "long" else "SHORT"
        top = (f"<div class='row'><div><span class='sym'>{e(r['symbol'])}</span> <span class='badge "
               f"{'b-up' if side == 'LONG' else 'b-dn'}'>{side}</span> <span class='ind'>{e(r['industry'])}</span></div>"
               f"<span class='badge {b}'>{e(st)}</span></div>")
        if "last" not in r:
            cards.append(f"<div class='card'>{top}</div>")
            continue
        info = (f"<div class='sub' style='margin-top:6px'>Last {money(r['last'])} "
                f"<span class='{cls(r.get('chg'))}'>{num(r.get('chg'), 2, True, '%')}</span>"
                f"{' · RS vs Nifty ' + num(r['rs'], 2, True, '%') if 'rs' in r else ''}"
                f"{' · OR ' + money(r['orl']) + '–' + money(r['orh']) if 'orh' in r else ''}"
                f"{' · VWAP ' + money(r['vwap']) if 'vwap' in r else ''}</div>")
        lv = ""
        if "entry" in r:
            lv = _lv([("Entry", money(r["entry"])), ("Stop", money(r["stop"])), ("T1 1.5R", money(r["t1"])),
                      ("T2 3R", money(r["t2"])), ("Qty", f"{r['qty']:,}"), ("Since", r["trigger_time"])])
            if r.get("extended"):
                lv += "<div class='warn'>⚠ Already more than 1R past entry - don't chase; wait for a pullback toward VWAP</div>"
        cards.append(f"<div class='card'>{top}{info}{lv}</div>")
    body = head + f"<div class='card'><div class='grid'>{k}</div></div>" + "".join(cards)
    return page(f"ORB {ctx['today']}", body)
